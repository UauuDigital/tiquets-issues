const I18N = (function () {
  const LANG_KEY = 'uauu_lang';
  const LOCALE_MAP = { ca: 'ca-ES', es: 'es-ES' };

  function getLang() {
    try {
      return localStorage.getItem(LANG_KEY) === 'es' ? 'es' : 'ca';
    } catch (err) {
      return 'ca';
    }
  }

  function getLocale() {
    return LOCALE_MAP[getLang()] || 'ca-ES';
  }

  function t(key, vars) {
    const lang = getLang();
    let str = (I18N_STRINGS[lang] && I18N_STRINGS[lang][key]) || I18N_STRINGS.ca[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
      });
    }
    return str;
  }

  function applyStaticTranslations(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
    document.documentElement.lang = getLang();
    document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
      btn.classList.toggle('active', btn.dataset.langBtn === getLang());
    });
  }

  function setLang(lang) {
    if (lang !== 'ca' && lang !== 'es') return;
    try { localStorage.setItem(LANG_KEY, lang); } catch (err) { /* localStorage no disponible */ }
    applyStaticTranslations();
    document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
  }

  document.addEventListener('click', (e) => {
    const btn = e.target.closest('[data-lang-btn]');
    if (btn) setLang(btn.dataset.langBtn);
  });

  applyStaticTranslations();

  return { getLang, getLocale, t, setLang, applyStaticTranslations };
})();
